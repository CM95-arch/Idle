# Turn the cut-out sprites (art/cut/, made by tools/slice_sheets.py) into the chunky pixel art the game draws:
# `python3 tools/pixelate.py [contactDir]`
# Each sprite is shrunk to its size in game pixels (the battle field is drawn at half resolution, so one art pixel
# is two field units), reduced to a small palette shared by all its frames (so colors don't flicker between them),
# given a hard edge and a dark one-pixel outline, and packed into one PNG atlas per sheet in assets/sprites/.
# Writes js/data/sprites.js: where every sprite is.
import json, os, sys
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CUT, OUT = os.path.join(ROOT, 'art', 'cut'), os.path.join(ROOT, 'assets', 'sprites')
# the box each kind fits in, in art pixels: heroes by height, creatures by max(height, 0.9 × width) to match how the
# battle sizes them, icons by their longer side
BOX = {'hero-back': 28, 'hero-front': 52, 'enemy': 24, 'boss': 50, 'icon': 24}
COLORS = {'hero-back': 20, 'hero-front': 20, 'enemy': 16, 'boss': 24, 'icon': 16}
INK = (24, 20, 32)
# the outline is a little see-through, so at small sizes it reads as an edge, not a black border
INK_A = 190


def fit(kind, w, h):
    if kind == 'icon': return BOX[kind] / max(w, h)
    if kind in ('enemy', 'boss'): return BOX[kind] / max(h, w * 0.9)
    return BOX[kind] / h


def pixelate(frames, kind):
    """All frames of one sprite, as pixel art of one size with one palette."""
    k = fit(kind, frames[0].width, frames[0].height)
    size = (max(1, round(frames[0].width * k)), max(1, round(frames[0].height * k)))
    small = [f.resize(size, Image.LANCZOS) for f in frames]
    # one palette for the whole animation
    strip = Image.new('RGB', (size[0] * len(small), size[1]))
    for i, s in enumerate(small):
        bg = Image.new('RGB', size, INK); bg.paste(s, mask=s.split()[3]); strip.paste(bg, (i * size[0], 0))
    pal = strip.quantize(COLORS[kind], method=Image.Quantize.MEDIANCUT)
    out = []
    for s in small:
        a = s.split()[3].point(lambda v: 255 if v > 120 else 0)
        rgb = s.convert('RGB').quantize(palette=pal, dither=Image.Dither.NONE).convert('RGBA')
        rgb.putalpha(a)
        p = Image.new('RGBA', (size[0] + 2, size[1] + 2), (0, 0, 0, 0)); p.paste(rgb, (1, 1))
        ring = p.split()[3].filter(ImageFilter.MaxFilter(3))
        ink = Image.new('RGBA', p.size, INK + (0,)); ink.putalpha(ring.point(lambda v: v * INK_A // 255))
        out.append(Image.alpha_composite(ink, p))
    return out


def main():
    contact = sys.argv[1] if len(sys.argv) > 1 else None
    idx = json.load(open(os.path.join(CUT, 'index.json')))
    src = [Image.open(os.path.join(CUT, a[0])).convert('RGBA') for a in idx['atlases']]
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT): os.remove(os.path.join(OUT, f))
    # keep the sheets' grouping: everything one screen shows tends to come from one sheet
    by_sheet = {}
    for key, s in idx['sprites'].items(): by_sheet.setdefault(s['frames'][0][0], []).append(key)
    atlases, table = [], {}
    for a, keys in sorted(by_sheet.items()):
        pieces = []
        for key in keys:
            S = idx['sprites'][key]
            frames = [src[fa].crop((x, y, x + w, y + h)) for fa, x, y, w, h in S['frames']]
            for i, im in enumerate(pixelate(frames, S['kind'])): pieces.append((key, i, im))
        pieces.sort(key=lambda p: -p[2].height)
        aw, x, y, shelf, placed = 512, 0, 0, 0, []
        for key, i, im in pieces:
            if x + im.width > aw: x, y, shelf = 0, y + shelf + 1, 0
            placed.append((key, i, im, x, y)); x += im.width + 1; shelf = max(shelf, im.height)
        atlas = Image.new('RGBA', (aw, y + shelf), (0, 0, 0, 0))
        for key, i, im, px, py in placed:
            atlas.paste(im, (px, py))
            table.setdefault(key, {})[i] = [len(atlases), px, py, im.width, im.height]
        name = idx['atlases'][a][0].replace('.webp', '.png')
        atlas.save(os.path.join(OUT, name), optimize=True)
        atlases.append([name, atlas.width, atlas.height])
    table = {k: [v[i] for i in sorted(v)] for k, v in sorted(table.items())}
    with open(os.path.join(ROOT, 'js', 'data', 'sprites.js'), 'w') as f:
        f.write('// Generated by tools/pixelate.py from the cut-outs in art/cut/. Do not edit by hand.\n')
        f.write('// Each sprite: its frames, each [atlas, x, y, w, h] in art pixels; an atlas is [file in assets/sprites/, width, height].\n')
        f.write(f'export const ATLASES = {json.dumps(atlases)};\n')
        f.write('export const SPRITES = {\n' + ''.join(f'  {json.dumps(k)}: {json.dumps(v)},\n' for k, v in table.items()) + '};\n')
    total = sum(os.path.getsize(os.path.join(OUT, a[0])) for a in atlases)
    print(f'{len(table)} pixel sprites, {len(atlases)} atlases, {total // 1024} KB')
    if contact:
        os.makedirs(contact, exist_ok=True)
        ims = [Image.open(os.path.join(OUT, a[0])) for a in atlases]
        for prefix, label in (('hero:', 'heroes'), ('mob:', 'creatures'), ('icon:', 'gear')):
            keys = [k for k in table if k.startswith(prefix)]
            cell = 80 if prefix != 'icon:' else 28
            cols = 16 if prefix != 'icon:' else 20
            per = 4 if prefix != 'icon:' else 1
            sheet = Image.new('RGBA', (cols * cell, ((len(keys) * per + cols - 1) // cols) * cell), (120, 124, 110, 255))
            n = 0
            for k in keys:
                for (fa, x, y, w, h) in table[k][:per] + table[k][:per - len(table[k][:per])]:
                    im = ims[fa].crop((x, y, x + w, y + h))
                    sheet.alpha_composite(im, ((n % cols) * cell + (cell - w) // 2, (n // cols) * cell + cell - h))
                    n += 1
            sheet = sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST)
            sheet.convert('RGB').save(os.path.join(contact, f'pixel-{label}.png'))


if __name__ == '__main__':
    main()
